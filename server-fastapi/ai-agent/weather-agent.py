def router_entry(state: AgentState) -> Literal["new_query", "followup"]:
    # If there is any previous AI message,
    # we consider this a followup, otherwise it's a new query
    # for msg in reversed(state["messages"]):
    #     if msg.type == "ai":
    #         return "followup"
    if state["topic"] is not None:
        return "followup"
    return "new_query"

def weather_agent():
    graph = StateGraph(AgentState)
    graph.add_node("first_message", first_message)
    graph.add_node("classify_query", classify_query)
    graph.add_node("initial_chatbot_for_weather", initial_chatbot_for_weather)
    graph.add_node("initial_chatbot_for_general_knowledge", initial_chatbot_for_general_knowledge)
    graph.add_node("get_weather_from_api", get_weather_from_api)
    graph.add_node("weather_explainer_chatbot", weather_explainer_chatbot)
    graph.add_node("chatbot_with_context", chatbot_with_context)
    
    graph.add_edge(START, "first_message")
    graph.add_conditional_edges(
        "first_message",
        router_entry,
        {
            "new_query": "classify_query",
            "followup": "chatbot_with_context"
        }
    )
    graph.add_conditional_edges(
        "classify_query",
        router,
        {
            "weather": "initial_chatbot_for_weather",
            "general knowledge": "initial_chatbot_for_general_knowledge",
            "unknown topic": END
        }
    )
    graph.add_edge("initial_chatbot_for_weather", "get_weather_from_api")
    graph.add_edge("get_weather_from_api", "weather_explainer_chatbot")
    graph.add_edge("weather_explainer_chatbot", END)
    graph.add_edge("initial_chatbot_for_general_knowledge", END)
    graph = graph.compile()
    return graph
    
