class ClassifierResponse(BaseModel):
    topic: str

# This function will classify the user's query as either "weather"
# or "general knowledge"
def classify_query(state: AgentState) -> AgentState:
    last_message = get_last_human_message(state)
    # last_message = state["messages"][-1].content
    llm = ChatCohere(
        cohere_api_key=COHERE_KEY,
        model="command-a-03-2025"
    )
    parser = PydanticOutputParser(
        pydantic_object=ClassifierResponse
    )
    prompt = ChatPromptTemplate.from_messages(
        [
            ("system",
            """ 
            Please classify the user's query into one of the following topics:
            - weather
            - general knowledge
            And answer only with topic : "weather" or "general knowledge".
            Wrap the output in this format and provide no other text:
            {format_instructions}
            """,
            ),
            ("human", "{query}"),
        ]
    # The format instructions are generated by the parser
    # and tell the LLM how to structure its output so that
    # it can be correctly parsed into the ResearchResponse object.
    ).partial(format_instructions=parser.get_format_instructions())

    chain = prompt | llm | parser
    
    response = chain.invoke({
        "query": last_message
    })

    print("The query is classified as: " + response.topic)
    new_topic = response.topic
    new_state = AgentState(messages=state["messages"], topic=new_topic)
    return new_state

def router(state: AgentState) -> Literal["weather", "general knowledge", "unknown topic"]:
    message_topic = state["topic"]

    if message_topic == "weather":
        return "weather"
    elif message_topic == "general knowledge":
        return "general knowledge"
    else:
        return "unknown topic"

